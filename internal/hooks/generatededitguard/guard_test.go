func TestDeclarationPrunesOldSessions(t *testing.T) {
	f := newFixture(t)
	st, err := openStore()
	if err != nil {
		t.Fatal(err)
	}
	if err := st.save("old", "reason", []string{f.path("gen.go")}, time.Now()); err != nil {
		t.Fatal(err)
	}
	old := time.Now().Add(-stateTTL - time.Hour)
	if err := os.Chtimes(st.sessionDir("old"), old, old); err != nil {
		t.Fatal(err)
	}
	expectInjection(t, f.bash("new", declare("gen.go")), hooktest.Options{})
	if _, err := os.Stat(st.sessionDir("old")); !os.IsNotExist(err) {
		t.Errorf("the expired session must be removed: %v", err)
	}
	if _, ok := st.lookup("new", f.path("gen.go")); !ok {
		t.Error("the new declaration must be recorded")
	}
	info, err := os.Stat(st.sessionDir("new"))
	if err != nil || info.Mode().Perm() != 0o700 {
		t.Errorf("session directory must be 0700: %v %v", info, err)
	}
}

