func declare(paths string) string {
	return "hhx " + DeclareCommand + " --reason 'the user asked to patch the generated file' " + paths
}

func TestDeclarationAllowsEditsInTheSameSession(t *testing.T) {
	f := newFixture(t)
	language := hooktest.Language
	declared := expectInjection(t, f.bash("session-a", declare("gen.go")), hooktest.Options{})
	if want := messages.T(language, idContextDeclared); !strings.Contains(declared, want) {
		t.Errorf("context %q does not contain %q", declared, want)
	}
	for _, want := range []string{"gen.go", "the user asked to patch the generated file", messages.T(language, idUnknownCommand)} {
		if !strings.Contains(declared, want) {
			t.Errorf("context %q does not contain %q", declared, want)
		}
	}

	for _, raw := range []string{
		f.payload("session-a", "Edit", map[string]any{"file_path": f.path("gen.go")}),
		f.bash("session-a", "echo x >> gen.go"),
		f.bash("session-a", "cd sub && echo x >> ../gen.go"),
	} {
		allowed := expectInjection(t, raw, hooktest.Options{})
		if want := messages.T(language, idContextAllowed); !strings.Contains(allowed, want) {
			t.Errorf("context %q does not contain %q", allowed, want)
		}
		if !strings.Contains(allowed, "the user asked to patch the generated file") {
			t.Errorf("context %q does not carry the declared reason", allowed)
		}
	}

	// 別のセッションと、宣言していないパスは止める。宣言したパスと一緒に書いても止める。
	expectDeny(t, f.payload("session-b", "Edit", map[string]any{"file_path": f.path("gen.go")}), hooktest.Options{})
	expectDeny(t, f.payload("session-a", "Edit", map[string]any{"file_path": f.path("sub/gen.go")}), hooktest.Options{})
	reason := expectDeny(t, f.bash("session-a", "echo x | tee gen.go x_mock.go"), hooktest.Options{}, "x_mock.go")
	if strings.Contains(reason, "Blocked: "+messages.Text(language, idTarget, map[string]any{"Files": "gen.go"})) {
		t.Errorf("the declared path must not be listed as blocked: %q", reason)
	}
}

