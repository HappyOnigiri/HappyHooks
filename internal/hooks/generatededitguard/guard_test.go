// l10nConfig は独自のマーカー（make l10n の生成物）を足す設定である。
const l10nConfig = "hooks:\n  generated-edit-guard:\n    markers:\n      - \"^// auto generate by 'make l10n'\"\n"

const (
	standardHeader = "// Code generated by acme-gen. DO NOT EDIT.\n\npackage acme\n"
	mockHeader     = "// Code generated by MockGen. DO NOT EDIT.\n// Source: acme.go\n//\n// Generated by this command:\n//\n" +
		"//\tmockgen -source=acme.go -destination=x_mock.go\n//\n\npackage acme\n"
	l10nHeader = "// auto generate by 'make l10n' on repository root directory.\npackage l10n\n"
)

// fixture は生成ファイルとそうでないファイルを置いた作業ディレクトリと、宣言の置き場である。
type fixture struct {
	dir string
}

func newFixture(t *testing.T) *fixture {
	t.Helper()
	tmp := hooktest.TempDir(t)
	t.Setenv("XDG_CACHE_HOME", filepath.Join(tmp, "cache"))
	f := &fixture{dir: filepath.Join(tmp, "work")}
	files := map[string]string{
		"gen.go":                             standardHeader,
		"x_mock.go":                          mockHeader,
		"infrastructure/l10n/resource_ja.go": l10nHeader,
		"infrastructure/l10n/translation.go": l10nHeader,
		"sub/gen.go":                         standardHeader,
		"plain.go":                           "package acme\n",
		"tmp.go":                             "package acme\n",
		"scripts/gen.py":                     "print('generate')\n",
	}
	for name, content := range files {
		hooktest.WriteFile(t, filepath.Join(f.dir, name), content)
	}
	return f
}

func (f *fixture) path(name string) string {
	return filepath.Join(f.dir, name)
}

// payload は session の PreToolUse の payload を作る。
func (f *fixture) payload(session, toolName string, toolInput any) string {
	data, err := json.Marshal(map[string]any{
		"session_id":      session,
		"transcript_path": "/dev/null",
		"hook_event_name": "PreToolUse",
		"tool_name":       toolName,
		"tool_input":      toolInput,
		"cwd":             f.dir,
	})
	if err != nil {
		panic(err)
	}
	return string(data)
}

func (f *fixture) bash(session, command string) string {
	return f.payload(session, "Bash", map[string]any{"command": command})
}

// invoke は payload で起動し、判定を返す。出力が注入なら、判断のフィールドが無いことを確かめて Injection も返す。
func invoke(t *testing.T, raw string, options hooktest.Options) (hooktest.Result, hooktest.Injection) {
	t.Helper()
	output := hooktest.Output(t, Definition(), raw, options)
	if strings.Contains(output, "permissionDecision") {
		return hooktest.Run(t, Definition(), raw, options), hooktest.Injection{}
	}
	return hooktest.Result{}, hooktest.ParseInjection(t, output)
}

func expectDeny(t *testing.T, raw string, options hooktest.Options, contains ...string) string {
	t.Helper()
	result, injection := invoke(t, raw, options)
	if result.Decision != hooktest.Deny {
		t.Fatalf("decision=%q, want deny (context %q) for %s", result.Decision, injection.Context, raw)
	}
	for _, text := range contains {
		if !strings.Contains(result.Reason, text) {
			t.Errorf("reason %q does not contain %q", result.Reason, text)
		}
	}
	return result.Reason
}

func expectSilent(t *testing.T, raw string, options hooktest.Options) {
	t.Helper()
	if output := hooktest.Output(t, Definition(), raw, options); output != "" {
		t.Errorf("want no output for %s, got %q", raw, output)
	}
}

func expectInjection(t *testing.T, raw string, options hooktest.Options) string {
	t.Helper()
	result, injection := invoke(t, raw, options)
	if result.Decision != "" || injection.Event != "PreToolUse" || injection.Context == "" {
		t.Fatalf("want an injection without a decision, got decision=%q injection=%+v (reason %q)",
			result.Decision, injection, result.Reason)
	}
	return injection.Context
}

